// Package manifest defines the portable manifest schema used to record
// directory snapshots. Manifests are JSON-serializable and include full
// path traversal protection and validation.
package manifest

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// CurrentSchemaVersion is the latest manifest schema version.
const CurrentSchemaVersion = 1

// Manifest is the top-level structure representing a directory snapshot.
type Manifest struct {
	// SchemaVersion is the manifest format version (currently 1).
	SchemaVersion int `json:"schema_version"`
	// SenvuVersion is the version of senvu that created this manifest.
	SenvuVersion string `json:"senvu_version"`
	// SnapshotID is a unique identifier (UUID) for this snapshot.
	SnapshotID string `json:"snapshot_id"`
	// CreatedAt is the time the snapshot was created.
	CreatedAt time.Time `json:"created_at"`
	// SourcePath is the relative path of the scanned directory.
	SourcePath string `json:"source_path"`
	// HashAlgorithm is the name of the hash algorithm used (e.g. "blake3").
	HashAlgorithm string `json:"hash_algorithm"`
	// Files is the list of file entries in the snapshot.
	Files []FileEntry `json:"files"`
	// TotalSize is the sum of all file sizes in bytes.
	TotalSize int64 `json:"total_size"`
	// TotalFiles is the number of files in the snapshot.
	TotalFiles int `json:"total_files"`
	// Metadata contains optional key-value metadata for the snapshot.
	Metadata map[string]string `json:"metadata,omitempty"`
}

// NewManifest creates a new empty Manifest for the given source path and hash algorithm.
func NewManifest(sourcePath, hashAlgorithm string) *Manifest {
	return &Manifest{
		SchemaVersion: CurrentSchemaVersion,
		SenvuVersion:  "0.1.0",
		SnapshotID:    "", // generated by snapshot service
		CreatedAt:     time.Now().UTC(),
		SourcePath:    sourcePath,
		HashAlgorithm: hashAlgorithm,
		Files:         make([]FileEntry, 0),
		Metadata:      make(map[string]string),
	}
}

// New is an alias for NewManifest.
func New(sourcePath, hashAlgorithm string) *Manifest {
	return NewManifest(sourcePath, hashAlgorithm)
}

// FileEntry represents a single file in the manifest.
type FileEntry struct {
	// RelPath is the forward-slash-normalized relative path.
	RelPath string `json:"rel_path"`
	// Size is the file size in bytes.
	Size int64 `json:"size"`
	// ModTime is the file's last modification time.
	ModTime time.Time `json:"mod_time"`
	// Hash is the hex-encoded hash digest.
	Hash string `json:"hash"`
	// Mode is the file permission mode.
	Mode os.FileMode `json:"mode"`
}

// Validate checks the manifest for internal consistency and security.
// It rejects invalid schema versions, empty hashes, path traversal
// attempts, and absolute paths.
func (m *Manifest) Validate() error {
	if m.SchemaVersion < 1 || m.SchemaVersion > CurrentSchemaVersion {
		return fmt.Errorf("unsupported schema version: %d (expected 1..%d)", m.SchemaVersion, CurrentSchemaVersion)
	}

	if m.SnapshotID == "" {
		return fmt.Errorf("snapshot ID must not be empty")
	}

	if m.HashAlgorithm == "" {
		return fmt.Errorf("hash algorithm must not be empty")
	}

	for i, f := range m.Files {
		if err := validatePath(f.RelPath); err != nil {
			return fmt.Errorf("file %d (%q): %w", i, f.RelPath, err)
		}
		if f.Hash == "" {
			return fmt.Errorf("file %d (%q): hash must not be empty", i, f.RelPath)
		}
	}

	return nil
}

// validatePath checks that a relative path is safe: no traversal and not absolute.
func validatePath(p string) error {
	if p == "" {
		return fmt.Errorf("path must not be empty")
	}

	// Reject absolute paths.
	if filepath.IsAbs(p) || strings.HasPrefix(p, "/") || (len(p) >= 2 && p[1] == ':') {
		return fmt.Errorf("path must be relative, got absolute: %q", p)
	}

	// Reject path traversal.
	cleaned := filepath.ToSlash(filepath.Clean(p))
	if strings.HasPrefix(cleaned, "../") || cleaned == ".." || strings.Contains(cleaned, "/../") || strings.HasSuffix(cleaned, "/..") {
		return fmt.Errorf("path traversal detected: %q", p)
	}

	// Also check individual components.
	parts := strings.Split(filepath.ToSlash(p), "/")
	for _, part := range parts {
		if part == ".." {
			return fmt.Errorf("path traversal detected: %q", p)
		}
	}

	return nil
}

// Save writes the manifest to path as pretty-printed JSON.
func (m *Manifest) Save(path string) error {
	if err := m.Validate(); err != nil {
		return fmt.Errorf("manifest validation failed: %w", err)
	}

	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return fmt.Errorf("marshaling manifest: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return fmt.Errorf("creating manifest directory: %w", err)
	}

	if err := os.WriteFile(path, data, 0644); err != nil {
		return fmt.Errorf("writing manifest file: %w", err)
	}

	return nil
}

// Load reads a manifest from path, unmarshals it, and validates it.
func Load(path string) (*Manifest, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading manifest file: %w", err)
	}

	var m Manifest
	if err := json.Unmarshal(data, &m); err != nil {
		return nil, fmt.Errorf("unmarshaling manifest: %w", err)
	}

	if err := m.Validate(); err != nil {
		return nil, fmt.Errorf("manifest validation: %w", err)
	}

	return &m, nil
}
